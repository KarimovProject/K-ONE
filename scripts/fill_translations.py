def load_source_strings() -> set[str]:
    import re

    pat_dq = re.compile(r'''{%\s*trans\s+"([^"]*)"''')
    pat_sq = re.compile(r"""{%\s*trans\s+'([^']*)'""")
    strings: set[str] = set()
    for path in (BASE_DIR / "templates").rglob("*.html"):
        content = path.read_text(encoding="utf-8")
        strings.update(pat_dq.findall(content))
        strings.update(pat_sq.findall(content))
    return {s for s in strings if not s.endswith("\\")}


def is_ascii_english(s: str) -> bool:
    try:
        s.encode("ascii")
    except UnicodeEncodeError:
        return False
    # Heuristic: Uzbek Latin text commonly reuses plain ASCII apostrophes for
    # o'/g' digraphs; treat strings with typical Uzbek function words as not-English.
    lowered = s.lower()
    uz_markers = (
        "tadbir", "zal", "bo'l", "qil", "kerak", "vaqt", "holat", "kanal",
        "guruh", "yerga", "yordam", "sozla", "yubor", "ulan", "band ",
        "erkin", "navbat", "hisob", "shaxsiy", "xabar", "yangi", "sana",
        "tasdiq", "bekor", "yopish", "ochish", "qidir", "filtr",
    )
    return not any(marker in lowered for marker in uz_markers)


def main() -> None:
    strings = load_source_strings()
    stats = {}
    for lang in ("uz", "en", "ru", "tr"):
        po_path = BASE_DIR / "locale" / lang / "LC_MESSAGES" / "django.po"
        po = polib.pofile(str(po_path))
        existing = {e.msgid for e in po}
        added = 0
        translated = 0
        for s in sorted(strings):
            entry = po.find(s)
            if entry is None:
                entry = polib.POEntry(msgid=s, msgstr="")
                po.append(entry)
                added += 1
            if entry.msgstr.strip():
                continue
            if lang == "uz":
                entry.msgstr = s  # uz is the base language: identity
                translated += 1
                continue
            mapping = TRANSLATIONS.get(s)
            if mapping and lang in mapping:
                entry.msgstr = mapping[lang]
                translated += 1
            elif lang == "en" and is_ascii_english(s):
                entry.msgstr = s  # already-English source string: identity
                translated += 1
        po.save(str(po_path))
        stats[lang] = (added, translated, len(po))
    for lang, (added, translated, total) in stats.items():
        print(f"{lang}: +{added} new entries, {translated} msgstr filled, {total} total")


if __name__ == "__main__":
    main()
